export function getProduct(id: string) {
  return products.find((p) => p.id === id)
}

export function getRelated(product: Product, count = 4) {
  return products
    .filter((p) => p.id !== product.id && (p.category === product.category || p.mood === product.mood))
    .slice(0, count)
}
